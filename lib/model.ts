// Token Radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every pre-token protocol the snapshot can honestly rank: the
// 40 watchlist slugs (the floor, never the ceiling) plus every other rankable
// pre-token protocol, above or below the floor, that is not a wrapped, staked
// or bridged product of a token that already trades. The house's watchlist
// rule is applied to the early rows too, so a staked-ETH clone or a bridge
// never poses as a launch candidate. A protocol is pre-token when its record
// carries no market cap, no CoinGecko id and no symbol.
//
// Implied value follows only from the snapshot's own figures, in four factors:
//
//   category multiple = the median market-cap-per-TVL-dollar of the LIVE
//     protocols in the same category (at least 3 of them), else the global
//     median across all live protocols; clamped to [0.05, 1.5]. The market
//     itself says what a TVL dollar is worth in each category, and the number
//     is recomputed from the snapshot on every run: no category value is
//     hard-coded, and no protocol name is ever special-cased.
//   growth  = clamp(change_7d, -60, 120) per cent; multiplier 1 + growth/100 x 0.6
//   maturity = 0.6 + min(age_days, 1095) / 1095 x 0.4  (age unknown: 365 days)
//   breadth = 1 + 0.02 x min(chains - 1, 5)   (a protocol on more chains reaches more users)
//   implied = max(1, round(tvl_usd x category x growth x maturity x breadth))
//
// Live-token protocols are kept apart and shown with their market caps, never
// mixed into the ranked board.

/** One protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

